// ⛔ The shared settings framework, loaded unconditionally — `Style_Presets` prints the
// widget's design tokens into `wp_head` on the FRONT end, so an `is_admin()` guard would
// leave every visitor looking at the unstyled fallbacks (§2.38).
require_once __DIR__ . '/class-zinn-reseller-admin-fields.php';
require_once __DIR__ . '/class-zinn-reseller-admin-ui.php';
require_once __DIR__ . '/class-zinn-reseller-connection.php';
require_once __DIR__ . '/class-zinn-reseller-diagnostics.php';
require_once __DIR__ . '/class-zinn-reseller-style-presets.php';
// Generated by `wp/bin/build-updater.php` — a global class, so it is addressed with a leading
// backslash from inside this namespace.
require_once __DIR__ . '/class-zinn-reseller-updater.php';
// AI agents (MCP, docs/901): through the shared MCP kit and the bundled WordPress MCP adapter.
require_once __DIR__ . '/mcp-kit/load.php';

add_action( 'plugins_loaded', __NAMESPACE__ . '\\zinn_reseller_boot' );
add_action( 'init', __NAMESPACE__ . '\\zinn_reseller_load_textdomain' );

// ── The Zinn® panel ──────────────────────────────────────────────────────────────────────
//
// ⚖️ Owner, 2026-09-01: *"each plugin should promote our hosting and marketplace as well as
// Zinn Hub global marketplace inside people's site in the admin dashboard"*, and *"user
// guides for them … linked to in the plugins dashboard"*.
//
// ⛔ `require_once` rather than the autoloader, and a STRING callable rather than
// `array( Zinn_Reseller_Promo::class, … )`. The class is deliberately global — it is shipped
// identically into seven plugins with different namespacing conventions, and three of them
// bootstrap inside a namespace where `Zinn_Reseller_Promo::class` would resolve to a class that does
// not exist. A string callable is resolved in the global namespace at call time, which is
// correct from every one of the seven. `php -l` cannot see that mistake; only running it can.
require_once __DIR__ . '/class-zinn-reseller-promo.php';
add_action( 'plugins_loaded', array( 'Zinn_Reseller_Promo', 'register' ) );
